// Rows below the digits' bottom, and 480 px per 360 px.
export const FONT = { below: 1, scale: 480 / 360 };

// How much ink each pixel of `text` gets, as the game draws it with digits
// `rows` high (9 or 10): 1 for a stroke, 0.95 for a stroke with nothing
// under it (its lower edge), and at 9 rows 0.6 for the shadow just right
// of a stroke. Returns { width, height, cover } with cover[y][x] in 0..1.
export function shade(text, rows = 9) {
  const set = MASKS[rows >= 10 ? 10 : 9];
  const height = set[0].length;
  const masks = [...text].map((c) => set[c]).filter(Boolean);
  const width = masks.reduce((sum, mask) => sum + mask[0].length + 1, 0);
  const ink = Array.from({ length: height }, () => new Array(width).fill(false));
  let left = 0;
  for (const mask of masks) {
    mask.forEach((row, y) => [...row].forEach((c, x) => { if (c === '#') ink[y][left + x] = true; }));
    left += mask[0].length + 1;
  }
  const cover = ink.map((row, y) => row.map((on, x) => {
    if (on) return y + 1 < height && ink[y + 1][x] ? 1 : 0.95;
    return set === MASKS[9] && x > 0 && row[x - 1] ? 0.6 : 0;
  }));
  return { width: Math.max(1, width), height, cover };
}
