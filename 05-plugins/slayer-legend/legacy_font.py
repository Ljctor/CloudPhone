@lru_cache(maxsize=32768)
def raster(glyph, origin, baseline, pen, left, right, height):
    """Bilinear texture sampling, including the tight atlas glyph's edges."""
    width, rows, bearing, top, _, bits = glyph
    gx = origin + (pen + bearing) * .5
    gy = baseline - top * .5
    columns = []
    for x in range(left, right):
        source = (x + .5 - gx) * 2
        if not 0 <= source < width:
            columns.append(None)
            continue
        source -= .5
        a = math.floor(source)
        columns.append((max(0, a), min(width - 1, a + 1), source - a))
    result = bytearray((right - left) * height)
    for y in range(height):
        source = (y + .5 - gy) * 2
        if not 0 <= source < rows:
            continue
        source -= .5
        a = math.floor(source)
        upper, lower = bits[max(0, a)], bits[min(rows - 1, a + 1)]
        fraction = source - a
        for x, column in enumerate(columns):
            if column is None:
                continue
            l, r, horizontal = column
            above = ((upper >> l & 1) * (1 - horizontal) + (upper >> r & 1) * horizontal) * 255
            below = ((lower >> l & 1) * (1 - horizontal) + (lower >> r & 1) * horizontal) * 255
            result[y * (right - left) + x] = int(above * (1 - fraction) + below * fraction)
    return bytes(result)


def screen(a, b):
    return bytes(255 - (255 - x) * (255 - y) // 255 for x, y in zip(a, b))



@lru_cache(maxsize=8)
def glyph_bank(vertical_bold=True, padding=2):
    bank={}
    for size,source in SOURCE_GLYPHS.items():
        bank[size]={}
        for char,(width,height,left,top,advance,rows) in source.items():
            if vertical_bold:
                rows=tuple((rows[y] if y<height else 0) | (rows[y-1] if y else 0)
                           for y in range(height+1))
                height+=1
            rows=(0,)*padding+tuple(row<<padding for row in rows)+(0,)*padding
            bank[size][char]=(width+2*padding,height+2*padding,left-padding,top+padding,advance,rows)
    return bank
